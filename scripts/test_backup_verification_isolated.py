#!/usr/bin/env python3
"""Explicit Linux synthetic-only restore checks; never connects to native PG."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import uuid

sys.path.insert(0,str(Path(__file__).resolve().parent))
import mdm_backup_verification as v


def main(image):
    if os.geteuid()!=0:raise RuntimeError('Docker test requires root')
    v.check_image(image)
    tag=uuid.uuid4().hex
    network='mdm-verify-synthetic-'+tag
    name='mdm-verify-synthetic-'+tag
    original=subprocess.run
    def call(args,**kw):
        return original(args,check=True,capture_output=True,timeout=60,**kw).stdout.decode().strip()
    with tempfile.TemporaryDirectory(prefix='mdm-verify-synthetic-',dir='/var/tmp') as folder:
        root=Path(folder);v.STATE=root/'state';v.EXPORT=root/'export';v.BACKUPS=root/'backups'
        for p in (v.STATE/'reports',v.STATE/'requests',v.EXPORT,v.BACKUPS):p.mkdir(parents=True)
        os.chmod(root,0o700)
        try:
            call(['docker','network','create','--internal','--label','cmab.mdm.synthetic='+tag,network])
            call(['docker','run','-d','--name',name,'--network',network,'--label','cmab.mdm.synthetic='+tag,
                  '--memory=512m','--memory-swap=512m','--cpus=1','--log-driver=none',
                  '-e','POSTGRES_HOST_AUTH_METHOD=trust','-e','POSTGRES_INITDB_ARGS=--locale=C.UTF-8',image])
            for _ in range(60):
                if original(['docker','exec',name,'pg_isready','-h','127.0.0.1','-U','postgres'],capture_output=True).returncode==0:break
                time.sleep(0.5)
            else:raise RuntimeError('synthetic source startup failed')
            sql='''CREATE DATABASE synthetic;'''
            call(['docker','exec',name,'psql','-U','postgres','-v','ON_ERROR_STOP=1','-c',sql])
            def source(sql):
                return call(['docker','exec',name,'psql','-X','-At','-U','postgres','-d','synthetic','-v','ON_ERROR_STOP=1','-c',sql])
            source("CREATE EXTENSION btree_gin; CREATE EXTENSION pg_trgm; CREATE EXTENSION pgcrypto; CREATE EXTENSION unaccent; CREATE SCHEMA mm; CREATE TABLE public.alembic_version(version_num text PRIMARY KEY); INSERT INTO public.alembic_version VALUES ('synthetic_v1'); CREATE TABLE mm.material(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE, status varchar NOT NULL DEFAULT 'draft', CONSTRAINT ck_status CHECK (status::text = ANY (ARRAY[('draft'::character varying)::text, ('published'::character varying)::text]))); INSERT INTO mm.material(name) VALUES ('合成物料甲'),('合成物料乙'); CREATE VIEW mm.material_view AS SELECT id,name FROM mm.material;")
            info=json.loads(call(['docker','inspect',name]))[0]
            ip=info['NetworkSettings']['Networks'][network]['IPAddress']
            if not ip:raise RuntimeError('synthetic source identity missing')
            os.environ['PG_DSN']='postgresql://postgres@'+ip+':5432/synthetic'
            artifact=v.BACKUPS/'cmab_mdm_synthetic_20261011_0000.dump'
            def concurrent(args,**kw):
                if args[0]=='pg_dump':source("INSERT INTO mm.material(name) VALUES ('合成备份期间新增')")
                return original(args,**kw)
            # Exported snapshot is held by the read-only producer while a
            # synthetic concurrent write occurs just before pg_dump starts.
            v.subprocess.run=concurrent
            try:request=v.snapshot_dump(artifact,6)
            finally:v.subprocess.run=original
            assert request['baseline']['table_counts']['mm.material']==2
            assert source('SELECT count(*) FROM mm.material')=='3'
            # Reproduce the historical deparser shape that triggered the real
            # failure, without connecting to native PG or changing real data.
            check=next(x for x in request['baseline']['constraints'] if x[2]=='ck_status')
            expanded="ARRAY[('draft'::character varying)::text, ('published'::character varying)::text]"
            compact="(ARRAY['draft'::character varying, 'published'::character varying])::text[]"
            historical=check[5].replace(expanded,compact)
            assert historical!=check[5],check
            assert v.canonical_check_definition(historical)==v.canonical_check_definition(check[5])
            check[5]=historical
            c={'image':image,'cpus':'1','memory':'512m','timeout_seconds':600}
            success=v.verify(request,c)
            assert success['status']=='passed' and success['integrity_status']=='verified',success
            mismatch=json.loads(json.dumps(request));mismatch['verification_id']=uuid.uuid4().hex
            mismatch['baseline']['table_counts']['mm.material']=99
            failed=v.verify(mismatch,c)
            assert failed['status']=='failed' and failed['failure_step']=='baseline_compare',failed
            constraint_mismatch=json.loads(json.dumps(request));constraint_mismatch['verification_id']=uuid.uuid4().hex
            changed=next(x for x in constraint_mismatch['baseline']['constraints'] if x[2]=='ck_status')
            changed[5]=changed[5].replace("'published'","'retired'")
            rejected=v.verify(constraint_mismatch,c)
            assert rejected['status']=='failed' and rejected['checks']['constraints']=='failed',rejected
            assert rejected['checks']['table_counts']=='passed',rejected
            damaged=v.BACKUPS/'cmab_mdm_synthetic_damaged.dump';damaged.write_bytes(b'invalid synthetic archive')
            bad=v.make_request(damaged,v.now(),v.now())
            broken=v.verify(bad,c)
            assert broken['status']=='failed' and broken['restore_status']=='failed',broken
            assert not call(['docker','ps','-aq','--filter','label='+v.LABEL])
            print(json.dumps({'synthetic_checks':'passed','same_snapshot_source_rows':3,
                              'backup_rows':2,'restore':success,'count_mismatch':'detected',
                              'equivalent_constraint':'passed','changed_constraint':'detected','invalid_archive':'detected','verification_containers_remaining':0},ensure_ascii=False))
        finally:
            # Only the exact generated synthetic name/network can be removed.
            original(['docker','rm','-fv',name],capture_output=True,timeout=30)
            original(['docker','network','rm',network],capture_output=True,timeout=30)
            os.environ.pop('PG_DSN',None)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--image',required=True)
    main(parser.parse_args().image)
